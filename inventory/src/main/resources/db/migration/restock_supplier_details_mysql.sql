CREATE TABLE SUPPLIER_ORDERS (
    ID BIGINT NOT NULL AUTO_INCREMENT,
    PRODUCT_ID VARCHAR(100) NOT NULL,
    PRODUCT_NAME VARCHAR(150) NOT NULL,
    SUPPLIER_ID VARCHAR(100) NOT NULL,
    SUPPLIER_NAME VARCHAR(150) NOT NULL,
    QUANTITY BIGINT NOT NULL,
    ORDER_DATE TIMESTAMP(6) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    MOVEMENT_ID BIGINT NULL,
    CONSTRAINT PK_SUPPLIER_ORDERS PRIMARY KEY (ID),
    CONSTRAINT FK_SUPPLIER_ORDERS_SUPPLIER FOREIGN KEY (SUPPLIER_ID) REFERENCES SUPPLIERS (ID),
    CONSTRAINT FK_SUPPLIER_ORDERS_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS (ID)
);
CREATE INDEX IDX_SUPPLIER_ORDERS_DATE ON SUPPLIER_ORDERS (ORDER_DATE);
CREATE INDEX IDX_SUPPLIER_ORDERS_STATUS ON SUPPLIER_ORDERS (STATUS);
